#region 2. See what you can reach --------------------------------------------
#   WHAT   List every enabled subscription the account can see.
#   WHY    The one you want may not be the default. Look before you set.
Get-AzSubscription | Where-Object State -eq 'Enabled' | Format-Table Name, Id, TenantId
#endregion

#region 3. Select the subscription -------------------------------------------
#   WHAT   Point the session at one subscription. Every later cmdlet uses it
#          unless told otherwise.
#   WHY    Running the right script against the wrong subscription is the
#          classic Azure mistake. Make the target explicit.
$step3Params = @{
    Subscription = '00000000-0000-0000-0000-000000000001'
}
Set-AzContext @step3Params
#endregion

#region 4. Verify ------------------------------------------------------------
#   WHAT   Read back what was created. Compare with what you asked for.
Get-AzContext | Format-List Account, Tenant, Subscription
#endregion
