#region 1. Sign in -----------------------------------------------------------
#   WHAT   Interactive sign-in. Skipped by Az if a cached token for this
#          tenant is still valid.
#   WHY    Nothing else works without a token. Passing the tenant avoids
#          landing in a guest tenant by accident.
