# Set-AzContext -Subscription '00000000-0000-0000-0000-000000000001'
Get-AzContext | Format-List Account, Tenant, Subscription
#endregion

# ===== Create a resource group ===============================================

#region 1. Create the resource group -----------------------------------------
#   WHAT   One ARM call. Idempotent: running it again for an existing group
#          with the same name and region is a no-op.
#   WHY    Every other Azure resource needs a group to live in, so this is
#          step one of almost every build.
$rgParams = @{
    Name     = 'rg-avd-lab'
    Location = 'eastus2'
}
# New-AzResourceGroup @rgParams -WhatIf    # uncomment for a dry run first
$rg = New-AzResourceGroup @rgParams
$rg
#endregion

# ===== Create a virtual network with one subnet ==============================

#region 2. Describe the subnet -----------------------------------------------
#   WHAT   Builds a subnet configuration object in memory. Nothing is created
#          in Azure yet.
#   WHY    New-AzVirtualNetwork takes subnets as objects, not names, so the
#          subnet is described first.
$subnetParams = @{
    Name          = 'snet-hosts'
    AddressPrefix = '10.10.1.0/24'
}
$subnet = New-AzVirtualNetworkSubnetConfig @subnetParams
$subnet
#endregion

#region 3. Create the virtual network ----------------------------------------
#   WHAT   Creates the VNet with the subnet from the previous step.
#   WHY    The VNet is the unit Azure deploys. The subnet rides along inside
#          it.
$vnetParams = @{
    Name              = 'vnet-avd-lab'
    ResourceGroupName = 'rg-avd-lab'
    Location          = 'eastus2'
    AddressPrefix     = '10.10.0.0/16'
    Subnet            = $subnet
}
# New-AzVirtualNetwork @vnetParams -WhatIf    # uncomment for a dry run first
$vnet = New-AzVirtualNetwork @vnetParams
$vnet
#endregion

#region 4. Keep the subnet ID for later --------------------------------------
#   WHAT   Reads the subnet resource ID off the VNet object that came back.
#   WHY    A VM NIC or an AVD session host needs the subnet ID, not its name.
#          Copy this value into the next task.
$subnetId = ($vnet.Subnets | Where-Object Name -eq 'snet-hosts').Id
$subnetId
#endregion

#region 5. Verify ------------------------------------------------------------
#   WHAT   Read back what was created. Compare with what you asked for.
Get-AzResourceGroup -Name 'rg-avd-lab' | Format-List ResourceGroupName, Location, ProvisioningState, Tags
Get-AzVirtualNetwork -Name 'vnet-avd-lab' -ResourceGroupName 'rg-avd-lab' | Select-Object Name, Location, @{ n = 'AddressSpace'; e = { $_.AddressSpace.AddressPrefixes } }, @{ n = 'Subnets'; e = { $_.Subnets.Name } }
#endregion

