<#
.SYNOPSIS
    Create a resource group, then Create a virtual network with one subnet
.DESCRIPTION
    A resource group is a lifecycle, RBAC, and cost boundary. Delete it and everything inside goes with it.
      - It is NOT a network, identity, or reference boundary. A VM in one group can use a subnet in another with nothing extra configured.
      - Decide the split before building. Moving resources between groups later works for most types but is never pleasant.
      - The group has a region of its own. That only decides where its metadata lives; resources inside can be anywhere.
    A VNet is a private address space in one region. Subnets carve it up; NICs attach to subnets. Nothing talks to anything without one.
      - Address spaces cannot overlap with anything you will peer or VPN to later. Pick from the 10.x range and leave room.
      - The subnet config object is built in memory first, then passed to New-AzVirtualNetwork. Azure reserves 5 addresses per subnet.
      - An NSG is separate. Create one and associate it in a later task; the VNet works without it, just with no filtering.
