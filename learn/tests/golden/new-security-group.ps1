    DisplayName     = 'AVD Users - Lab'
    MailNickname    = 'avd-users-lab'
    SecurityEnabled = $true
    MailEnabled     = $false
    GroupTypes      = @()
}
# New-MgGroup @groupParams -WhatIf    # uncomment for a dry run first
$group = New-MgGroup @groupParams
$group
