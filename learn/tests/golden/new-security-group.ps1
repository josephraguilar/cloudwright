#region 1. Create the group --------------------------------------------------
#   WHAT   POST /groups with securityEnabled true and mailEnabled false.
#          Returns the new group with its Id.
#   WHY    The object Id that comes back is what every later assignment
#          (license, role, AVD app group) needs. Keep it.
